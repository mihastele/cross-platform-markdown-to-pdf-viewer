#!/usr/bin/env python3
"""Generates crates/mdpdf-core/src/metrics_data.rs from the standard-14 font
width tables shipped with reportlab (WinAnsi code -> advance width, 1/1000 em).
Run once; the output is checked in so the build has no Python dependency."""
from reportlab.pdfbase import pdfmetrics

FONTS = [
    "Helvetica", "Helvetica-Bold", "Helvetica-Oblique", "Helvetica-BoldOblique",
    "Times-Roman", "Times-Bold", "Times-Italic", "Times-BoldItalic",
    "Courier", "Courier-Bold", "Courier-Oblique", "Courier-BoldOblique",
]
out = ["// @generated by tools/gen_font_metrics.py -- do not edit.",
       "// Advance widths (1/1000 em) for WinAnsi codes 0..=255.", ""]
for name in FONTS:
    w = pdfmetrics.getFont(name).widths
    assert len(w) == 256
    ident = name.upper().replace("-", "_")
    out.append(f"pub static {ident}: [u16; 256] = [")
    for i in range(0, 256, 16):
        out.append("    " + ", ".join(str(int(x)) for x in w[i:i+16]) + ",")
    out.append("];\n")
print("\n".join(out))
